    private readonly string _root;

    public MacroFileLoadDirectiveMigratorTests()
    {
        _root = Path.Combine(
            Path.GetTempPath(),
            "Macros.Tests.Migrator",
            Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(_root);
    }

    public void Dispose()
    {
        try
        {
            if (Directory.Exists(_root))
            {
                Directory.Delete(_root, recursive: true);
            }
        }
        catch
        {
            // Best-effort cleanup.
        }
    }

    // ── helpers ───────────────────────────────────────────────────────────────────────

    private string Write(string name, string content)
    {
        string path = Path.Combine(_root, name);
        File.WriteAllText(path, content);
        return path;
    }

    private string Read(string name) => File.ReadAllText(Path.Combine(_root, name));

    /// <summary>
    /// Writes <paramref name="content"/> to <c><see cref="_root"/>\<paramref name="relativePath"/></c>,
    /// creating intermediate directories as needed.
    /// </summary>
    private string WriteAt(string relativePath, string content)
    {
        string path = Path.Combine(_root, relativePath);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content);
        return path;
    }

    private string ReadAt(string relativePath) => File.ReadAllText(Path.Combine(_root, relativePath));

    /// <summary>
    /// Minimal pre-shim macro: header comments, #r directives, usings, body.
    /// Represents a file recorded before commit 12056f1.
    /// </summary>
    private static string PreShimMacro(string nl = "\n") =>
        string.Join(nl, new[]
        {
            "// Macro: OldMacro",
            "// Recorded: 2025-01-01T00:00:00Z",
            "// Steps: 1",
            "// Generated by Macros \u2014 edit freely.",
            "// Source format: C# Script (.csx) \u2014 executed by Macros.Engine.Player.MacroPlayer.",
            "//",
            "// Trigger guidance here.",
            "//",
            "",
            "// #r directives below are kept for external dotnet-script consumers; MacroPlayer",
            "// supplies the same references via ScriptOptions at compile time.",
            "#r \"EnvDTE\"",
            "#r \"EnvDTE80\"",
            "",
            "using System;",
            "using EnvDTE;",
            "",
            "// step 1: insert 5 char(s) @ pos 0",
            "await TypeAsync(\"Hello\");",
            "",
        }) + nl;   // preserve final newline

