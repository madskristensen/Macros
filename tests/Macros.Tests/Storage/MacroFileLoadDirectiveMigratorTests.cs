    // ── 15. Round-trip is Roslyn-parseable ───────────────────────────────────────

    [Fact]
    public void Migrate_RoundTripIsRoslynParseable()
    {
        // Generate a fresh macro with the current codegen.
        var steps = new RecordedStep[]
        {
            new TextEditStep(0, 0, "", "hello"),
            new RecordedStep.CommandStep(Guid.NewGuid(), 1u, "Edit.Copy"),
        };
        DateTime utc = new DateTime(2026, 5, 1, 23, 30, 25, DateTimeKind.Utc);
        string freshSource = CSharpCodeGenerator.Generate(steps, "RoundTrip", utc);

        // Simulate a pre-shim file by removing the entire shim block emitted by
        // EmitReferenceDirectives (comment + #load + usings + blank line).
        const string shimCommentLine = "// IntelliSense + script globals come from this shim (auto-generated by the Macros VSIX).\n";
        int blockBegin = freshSource.IndexOf(shimCommentLine, StringComparison.Ordinal);
        Assert.True(blockBegin >= 0, "Fresh codegen output should contain the shim comment line.");

        // Find the blank line that terminates the block (after the usings).
        // The block ends at the first blank line after blockBegin.
        int searchPos = blockBegin;
        int blockEnd = blockBegin;
        while (searchPos < freshSource.Length)
        {
            int nlPos = freshSource.IndexOf('\n', searchPos);
            if (nlPos < 0) { blockEnd = freshSource.Length; break; }
            string line = freshSource.Substring(searchPos, nlPos - searchPos);
            if (searchPos > blockBegin && line.Trim().Length == 0)
            {
                blockEnd = nlPos + 1; // include the blank line's newline
                break;
            }
            searchPos = nlPos + 1;
        }

        string preShimSource = freshSource.Remove(blockBegin, blockEnd - blockBegin);

        Write("roundtrip.csx", preShimSource);
        MacroFileLoadDirectiveMigrator.Migrate(_root);
        string migrated = Read("roundtrip.csx");

        // 1. The #load directive is present after migration.
        Assert.Contains("#load \".intellisense/Macros.Intellisense.csx\"", migrated);

        // 2. Roslyn can parse the migrated content without syntax errors.
        AssertNoSyntaxErrors(migrated);

        // 3. The macro body is preserved.
        Assert.Contains("await TypeAsync(\"hello\");", migrated);
        Assert.Contains("await ExecuteCommandAsync(\"Edit.Copy\");", migrated);
    }

