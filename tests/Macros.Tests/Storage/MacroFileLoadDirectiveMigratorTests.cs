    // ── 13. Per-file error captured; other files still processed ─────────────────

    [Fact]
    public void Migrate_PerFileErrorIsCaptured_OthersStillProcessed()
    {
        // Write two macro files; lock one to cause a read failure.
        string goodPath = Write("good.csx", PreShimMacro());
        string badPath  = Write("bad.csx",  PreShimMacro());

        MigrationResult result;

        // Hold bad.csx open with FileShare.None to prevent the migrator from reading it.
        using (var lockStream = new FileStream(badPath, FileMode.Open, FileAccess.ReadWrite, FileShare.None))
        {
            result = MacroFileLoadDirectiveMigrator.Migrate(_root);
        }

        Assert.Equal(2, result.Scanned);

        // Exactly one error for the locked file.
        string singleError = Assert.Single(result.Errors);
        Assert.Contains("bad.csx", singleError);

        // The good file was still updated.
        Assert.Equal(1, result.Updated);

        // Invariant: Scanned == Updated + Skipped + Errors.Count
        Assert.Equal(result.Scanned, result.Updated + result.Skipped + result.Errors.Count);
    }

